std::filesystem::path RunfilePath(const std::string &relative_path) {
  const char *const test_srcdir = std::getenv("TEST_SRCDIR");
  if (test_srcdir != nullptr && test_srcdir[0] != '\0') {
    return std::filesystem::path(test_srcdir) / "_main" / relative_path;
  }
  return std::filesystem::path(relative_path);
}

bool ReadReferenceOutput(const std::string &filename, std::string *const output) {
  OMNI_RETURN_VAL_IF(output == nullptr, false);
  const std::filesystem::path path = RunfilePath("test/inference/" + filename);
  std::ifstream stream(path, std::ios::binary);
  OMNI_RETURN_VAL_IF(!stream.good(), false);
  output->assign(std::istreambuf_iterator<char>(stream), std::istreambuf_iterator<char>());
  return stream.good() || stream.eof();
}

void PrintPerformance(const omni_runtime::inference::GenerationResult &result) {
  std::ostringstream report;
  report << std::fixed << std::setprecision(2) << "Model infer Time:\n"
         << "  VIT:\n"
         << "    Input image (W x H): " << result.input_image_size.width_pixels << " x "
         << result.input_image_size.height_pixels << " pixels\n"
         << "    Resized image (W x H): " << result.resized_image_size.width_pixels << " x "
         << result.resized_image_size.height_pixels << " pixels\n"
         << "    Time: " << result.vision_time_ms << " ms\n"
         << "  Prefill:\n"
         << "    Input tokens: " << result.prefill_token_count << '\n'
         << "    Time: " << result.prefill_time_ms << " ms\n"
         << "    Throughput: " << result.prefill_tokens_per_second() << " tokens/s\n"
         << "  Decode:\n"
         << "    Generated token IDs: " << result.generated_token_ids.size() << '\n'
         << "    Timed decode tokens: " << result.decode_token_count
         << " (first token is generated by prefill)\n"
         << "    Time: " << result.decode_time_ms << " ms\n"
         << "    Throughput: " << result.decode_tokens_per_second() << " tokens/s\n";
  std::cout << report.str() << std::flush;
}

