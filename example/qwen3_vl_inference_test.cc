class Qwen3VLInferenceTest : public ::testing::Test {
protected:
  static void SetUpTestSuite() {
    pipeline_ = std::make_unique<qwen3_vl::Qwen3VLPipeline>();
    ASSERT_TRUE(
        pipeline_->Init(RunfilePath("Omni-Runtime/inference/conf/qwen3_vl_8B_f16.conf").string()))
        << pipeline_->error_message();
  }

  static void TearDownTestSuite() {
    pipeline_.reset();
  }

  static inline std::unique_ptr<qwen3_vl::Qwen3VLPipeline> pipeline_;
};

TEST_F(Qwen3VLInferenceTest, MatchesFp16ReferenceOutput) {
  auto &pipeline = *pipeline_;
  GenerationRequest request;
  request.prompt = "Describe this image.";
  request.image_path = RunfilePath("test/inference/demo.jpeg").string();

  GenerationResult result;
  std::string streamed_text;
  size_t callback_count = 0U;
  bool has_generate_returned = false;
  request.stream_callback = [&](const std::string &chunk) {
    EXPECT_FALSE(has_generate_returned);
    EXPECT_FALSE(chunk.empty());
    ++callback_count;
    streamed_text += chunk;
    std::cout << chunk << std::flush;
    return true;
  };
  const auto generate = [&](const int32_t max_new_tokens, const std::string &description) {
    request.max_new_tokens = max_new_tokens;
    streamed_text.clear();
    callback_count = 0U;
    has_generate_returned = false;
    std::cout << '\n' << description << '\n' << std::flush;
    const bool is_successful = pipeline.Generate(request, &result);
    has_generate_returned = true;
    std::cout << "\n\n";
    OMNI_RETURN_VAL_IF(!is_successful, false);
    EXPECT_GT(callback_count, 1U);
    EXPECT_EQ(streamed_text, result.text);
    EXPECT_FALSE(result.is_cancelled);
    EXPECT_EQ(result.input_image_size.width_pixels, 2048);
    EXPECT_EQ(result.input_image_size.height_pixels, 1365);
    EXPECT_EQ(result.resized_image_size.width_pixels, 2048);
    EXPECT_EQ(result.resized_image_size.height_pixels, 1376);
    EXPECT_EQ(result.vision_token_count, 2752);
    EXPECT_EQ(result.prefill_token_count, 2766);
    EXPECT_EQ(result.decode_token_count + 1, result.generated_token_ids.size());
    EXPECT_GT(result.vision_time_ms, 0.0);
    EXPECT_GT(result.prefill_tokens_per_second(), 0.0);
    EXPECT_GT(result.decode_tokens_per_second(), 0.0);
    PrintPerformance(result);
    return true;
  };
  ASSERT_TRUE(generate(64, "FP16 reference (64-token limit, first run, streaming):"))
      << pipeline.error_message();

  std::string expected_output;
  ASSERT_TRUE(ReadReferenceOutput("qwen3_vl_8b_fp16.txt", &expected_output));
  std::ifstream token_stream(RunfilePath("test/inference/qwen3_vl_8b_fp16.tokens"));
  ASSERT_TRUE(token_stream.good());
  const std::vector<int32_t> expected_token_ids{std::istream_iterator<int32_t>(token_stream),
                                                std::istream_iterator<int32_t>()};
  ASSERT_EQ(expected_token_ids.size(), 64U);
  EXPECT_EQ(result.generated_token_ids.size(), 64U);
  EXPECT_EQ(result.decode_token_count, 63);
  EXPECT_EQ(result.generated_token_ids, expected_token_ids);
  EXPECT_EQ(result.text, expected_output);

  const size_t gpu_memory_bytes = result.gpu_memory_bytes;
  ASSERT_TRUE(generate(1024, "Reused graph (1024-token limit, streaming):"))
      << pipeline.error_message();
  ASSERT_TRUE(ReadReferenceOutput("qwen3_vl_8b_fp16_long.txt", &expected_output));
  std::ifstream long_tokens(RunfilePath("test/inference/qwen3_vl_8b_fp16_long.tokens"));
  ASSERT_TRUE(long_tokens.good());
  const std::vector<int32_t> expected_long_ids{std::istream_iterator<int32_t>(long_tokens),
                                               std::istream_iterator<int32_t>()};
  EXPECT_EQ(result.generated_token_ids, expected_long_ids);
  EXPECT_EQ(result.decode_token_count, 351);
  EXPECT_EQ(result.text, expected_output);
  EXPECT_EQ(result.gpu_memory_bytes, gpu_memory_bytes);
  ASSERT_FALSE(result.generated_token_ids.empty());
  EXPECT_EQ(result.generated_token_ids.back(),
            pipeline.model_config().special_tokens.end_of_sequence_id);
}

TEST_F(Qwen3VLInferenceTest, CancelsAndResumesTextGeneration) {
  auto &pipeline = *pipeline_;
  GenerationRequest request;
  request.prompt = "Describe this image.";
  request.max_new_tokens = 8;
  GenerationResult result;
  std::string streamed_text;
  size_t callback_count = 0U;
  request.stream_callback = [&](const std::string &chunk) {
    streamed_text += chunk;
    ++callback_count;
    return false;
  };
  ASSERT_TRUE(pipeline.Generate(request, &result)) << pipeline.error_message();
  EXPECT_TRUE(result.is_cancelled);
  EXPECT_EQ(callback_count, 1U);
  EXPECT_EQ(result.generated_token_ids.size(), 1U);
  EXPECT_EQ(result.text, streamed_text);
  EXPECT_EQ(result.decode_token_count, 0);
  EXPECT_EQ(result.decode_time_ms, 0.0);
  EXPECT_EQ(result.decode_tokens_per_second(), 0.0);
  EXPECT_EQ(result.vision_time_ms, 0.0);
  EXPECT_EQ(result.input_image_size.width_pixels, 0);
  EXPECT_EQ(result.input_image_size.height_pixels, 0);
  EXPECT_EQ(result.resized_image_size.width_pixels, 0);
  EXPECT_EQ(result.resized_image_size.height_pixels, 0);

  const size_t gpu_memory_bytes = result.gpu_memory_bytes;
  request.max_new_tokens = 1;
  request.stream_callback = {};
  ASSERT_TRUE(pipeline.Generate(request, &result)) << pipeline.error_message();
  EXPECT_FALSE(result.is_cancelled);
  EXPECT_EQ(result.generated_token_ids.size(), 1U);
  EXPECT_EQ(result.text, streamed_text);
  EXPECT_EQ(result.decode_token_count, 0);
  EXPECT_EQ(result.decode_time_ms, 0.0);
  EXPECT_EQ(result.gpu_memory_bytes, gpu_memory_bytes);
}

TEST_F(Qwen3VLInferenceTest, RejectsReentryAndReportsCallbackExceptions) {
  auto &pipeline = *pipeline_;
  GenerationRequest request;
  request.prompt = "Describe this image.";
  request.max_new_tokens = 1;
  GenerationResult result;
  request.stream_callback = [&](const std::string &) {
    GenerationResult nested_result;
    EXPECT_FALSE(pipeline.Generate(request, &nested_result));
    return true;
  };
  bool is_successful = false;
  ::testing::internal::CaptureStderr();
  EXPECT_NO_THROW(is_successful = pipeline.Generate(request, &result));
  const std::string reentry_log = ::testing::internal::GetCapturedStderr();
  EXPECT_TRUE(is_successful) << pipeline.error_message();
  EXPECT_EQ(reentry_log, "[2] Cannot reenter generation from a stream callback\n");

  request.stream_callback = [](const std::string &) -> bool {
    throw std::runtime_error("stream callback test error");
  };
  ::testing::internal::CaptureStderr();
  EXPECT_NO_THROW(is_successful = pipeline.Generate(request, &result));
  const std::string callback_log = ::testing::internal::GetCapturedStderr();
  EXPECT_FALSE(is_successful);
  EXPECT_EQ(callback_log, "[2] Text stream callback failed: stream callback test error\n");
  EXPECT_NE(pipeline.error_message().find("stream callback test error"), std::string::npos);
  request.stream_callback = {};
  ASSERT_TRUE(pipeline.Generate(request, &result)) << pipeline.error_message();
  EXPECT_FALSE(result.is_cancelled);
}

